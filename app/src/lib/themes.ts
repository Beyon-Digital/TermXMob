export type ThemeKind = "dark" | "light";

export type ThemeUi = {
  background: string;
  surface: string;
  surfaceAlt: string;
  surfaceActive: string;
  border: string;
  text: string;
  textMuted: string;
  accent: string;
  accentText: string;
  danger: string;
};

export type StatusColors = {
  success: string;
  warning: string;
  info: string;
  scrim: string;
};

export function statusColors(ui: ThemeUi, kind: ThemeKind): StatusColors {
  return {
    success: ui.accent,
    warning: kind === "dark" ? "#f5c542" : "#b8860b",
    info: kind === "dark" ? "#7eb6ff" : "#0b57d0",
    scrim: kind === "dark" ? "rgba(0,0,0,0.55)" : "rgba(0,0,0,0.32)",
  };
}

