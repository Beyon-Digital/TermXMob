export function findTheme(themes: AppTheme[], id: string): AppTheme | undefined {
  return themes.find((theme) => theme.id === id);
}

export function themeWithDerivedTerminal(theme: AppTheme): AppTheme {
  const ui = theme.ui;
  return {
    ...theme,
    terminal: {
      ...theme.terminal,
      background: ui.background,
      foreground: ui.text,
      cursor: ui.accent,
      selectionBackground: ui.surfaceActive,
    },
  };
}
