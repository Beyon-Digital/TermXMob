import {render,screen,fireEvent,cleanup,waitFor,act} from '@testing-library/react';
import {afterEach,it,expect,vi} from 'vitest';
import Workbench from './Workbench';
import {request,type Session} from '../lib/api';
vi.mock('../lib/api',()=>({gql:vi.fn(),request:vi.fn(),json:(method:string,data:unknown)=>({method,body:JSON.stringify(data)})}));
vi.mock('./TerminalPanel',()=>({default:()=>null}));
vi.mock('./Debugger',()=>({default:()=>null}));
vi.mock('./Delivery',()=>({default:()=>null}));
vi.mock('./Preview',()=>({default:()=>null}));
vi.mock('../lib/lsp',()=>({LanguageClient:class{},fileUri:()=>'',positionAt:()=>({line:0,character:0})}));
afterEach(()=>{cleanup();vi.clearAllMocks()});
const project={id:'project',name:'Fixture',path:'/fixture'};
const session:Session={id:'chat',cwd:'/fixture',project_id:'project',worktree_id:null,title:'Chat',engine:'internal',mode:'ask',pinned:false,archived:false,draft_text:'',revision:1,updated_at:0,scroll:0};
it('expands folders in place, keeps the active file while the explorer is collapsed, and reveals advanced commands on demand',async()=>{
 vi.mocked(request).mockImplementation(async path=>{if(path.includes('/delivery'))return {worktrees:[]} as any;const params=new URLSearchParams(path.split('?')[1]);if(params.get('operation')==='read')return {path:'src/main.txt',content:'Real nested file',revision:'v1',editable:true} as any;return {entries:params.get('path')==='src'?[{name:'main.txt',path:'src/main.txt'}]:[{name:'src',path:'src',directory:true},{name:'README.md',path:'README.md'}]} as any});
 const view=render(<Workbench project={project} session={session} visible bottom onError={()=>{}}/>);
 expect(screen.queryByLabelText('Editor split layout')).not.toBeInTheDocument();
 const folderButton=(await screen.findByText('src')).closest('button')!;
 fireEvent.click(folderButton);
 expect(folderButton).toHaveAttribute('aria-expanded','true');
 fireEvent.click(await screen.findByText('main.txt'));
 await waitFor(()=>expect(view.container.querySelector('.cm-content')).toHaveTextContent('Real nested file'));
 expect(screen.getByLabelText('File path')).toHaveTextContent('srcmain.txt');
 expect(screen.getByText('README.md')).toBeVisible();
 fireEvent.click(screen.getByLabelText('Hide explorer'));
 expect(screen.getByLabelText('Explorer')).not.toBeVisible();
 expect(view.container.querySelector('.cm-content')).toHaveTextContent('Real nested file');
 fireEvent.click(screen.getByLabelText('Show explorer'));
 expect(folderButton).toHaveAttribute('aria-expanded','true');
 fireEvent.click(screen.getByLabelText('Editor actions'));
 expect(screen.getByLabelText('Editor split layout')).toBeVisible();
 expect(screen.getByText('Go to definition')).toBeVisible();
 fireEvent.keyDown(document,{key:'Escape'});
 expect(screen.queryByLabelText('Editor split layout')).not.toBeInTheDocument();
 fireEvent.click(screen.getByText('Problems'));
 expect(screen.getByText('No problems reported by the language server.')).toBeVisible();
 screen.getByText('Problems').focus();
 fireEvent.keyDown(screen.getByText('Problems'),{key:'ArrowRight'});
 expect(screen.getByText('Run & debug')).toHaveAttribute('aria-selected','true');
});
it('ignores directory children that finish loading after the checkout changes',async()=>{
 let release!:(data:unknown)=>void;
 vi.mocked(request).mockImplementation(async path=>{if(path.includes('/delivery'))return {worktrees:[]} as any;const params=new URLSearchParams(path.split('?')[1]);if(params.get('path')==='src')return new Promise(resolve=>{release=resolve});return {entries:params.get('worktree_id')==='other'?[]:[{name:'src',path:'src',directory:true}]} as any});
 const view=render(<Workbench project={project} session={session} visible bottom={false} onError={()=>{}}/>);
 fireEvent.click(await screen.findByText('src'));
 await waitFor(()=>expect(release).toBeDefined());
 view.rerender(<Workbench project={project} session={{...session,cwd:'/other',worktree_id:'other'}} visible bottom={false} onError={()=>{}}/>);
 await act(async()=>release({entries:[{name:'stale.txt',path:'src/stale.txt'}]}));
 expect(screen.queryByRole('button',{name:'stale.txt'})).not.toBeInTheDocument();
 expect(screen.queryByRole('button',{name:'src'})).not.toBeInTheDocument();
});
