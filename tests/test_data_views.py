def C(alias, column):
    return {'table_alias': alias, 'column': column}


def F(column, op, **kw):
    return {'field': C('s', column), 'op': op, **kw}


def AND(*items):
    return {'op': 'and', 'items': list(items)}


def REF(sid, negate=False):
    return {'segment': sid, 'negate': negate}


def spec(cid, **kw):
    body = {'version': 1, 'source': cid, 'from': {'table': 'sales', 'alias': 's'}, 'joins': [], 'select': [C('s', 'id'), C('s', 'region'), C('s', 'amount')],
            'filters': AND(), 'group_by': [], 'aggregates': [], 'sort': [{**C('s', 'id'), 'direction': 'asc'}], 'limit': 200, 'offset': 0}
    body.update(kw)
    return body


def segment_spec(cid, *filters):
    return spec(cid, select=[], sort=[], filters=AND(*filters))


def pivot_spec(cid, rows=('region',), columns=None, fn='count', measure=None, **kw):
    value = {'fn': fn, **({'table_alias': 's', 'column': measure} if measure else {})}
    pivot = {'rows': [C('s', r) if isinstance(r, str) else r for r in rows],
             'columns': C('s', columns) if isinstance(columns, str) else columns, 'value': value, 'totals': True,
             'sort': {'by': 'rows', 'direction': 'asc'}}
    return spec(cid, select=[], sort=[], pivot=pivot, **kw)


def month(column='day'):
    return {**C('s', column), 'bucket': 'month'}


