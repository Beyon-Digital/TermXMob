def run_threads(jobs):
    barrier = threading.Barrier(len(jobs))
    results = [None] * len(jobs)

    def worker(i, job):
        barrier.wait()
        try:
            results[i] = ('ok', job())
        except HTTPException as error:
            results[i] = ('error', error)
    threads = [threading.Thread(target=worker, args=(i, job)) for i, job in enumerate(jobs)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    return results


def test_two_simultaneous_patches_with_the_same_revision_one_wins(env):
    views = env.service.views
    for round_ in range(10):
        view = table_view(env, f'Race {round_}')
        results = run_threads([
            lambda who=who: asyncio.run(views.update(env.actors[who], env.wid, view['id'], 1, f'{who} {round_}', None, None))
            for who in ('alice', 'bob')])
        outcomes = sorted(kind for kind, _ in results)
        assert outcomes == ['error', 'ok'], results
        loser = next(value for kind, value in results if kind == 'error')
        assert loser.status_code == 409 and loser.detail['code'] == 'revision_conflict'
        assert call(env, 'GET', '/views/' + view['id']).json()['revision'] == 2


