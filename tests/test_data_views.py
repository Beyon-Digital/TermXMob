def test_contract_fixtures_match_the_backend(env):
    files = scenario(env)
    if os.environ.get('TERMX_UPDATE_FIXTURES'):
        FIXTURES.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            (FIXTURES / name).write_text(json.dumps(content, indent=2, ensure_ascii=False) + '\n')
    stored = {f.name: json.loads(f.read_text()) for f in FIXTURES.glob('*.json')} if FIXTURES.exists() else {}
    assert set(stored) == set(files), 'run with TERMX_UPDATE_FIXTURES=1 to create them'
    for name, content in files.items():
        assert content == stored[name], name
    assert stored['view-conflict.json']['response']['detail']['code'] == 'revision_conflict'
