ISO = re.compile(r'^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?\+00:00$')


class Scenario:
    """Runs one deterministic story and records each request and response with ids and times replaced by placeholders."""

    def __init__(self, env):
        self.env, self.names, self.files = env, {}, {}
        self.names.update({env.cid: 'conn_01', env.wid: 'ws_01', env.actors['alice'].id: 'p_alice', env.actors['bob'].id: 'p_bob',
                           env.actors['vera'].id: 'p_vera'})

    def norm(self, value):
        if isinstance(value, dict):
            return {self.norm(k) if isinstance(k, str) else k: self.norm(v) for k, v in value.items() if k != 'schema_hash'} | \
                ({'schema_hash': '<hash>'} if 'schema_hash' in value else {})
        if isinstance(value, list):
            return [self.norm(v) for v in value]
        if isinstance(value, str):
            for real, placeholder in self.names.items():
                value = value.replace(real, placeholder)
            return '<time>' if ISO.match(value) else re.sub(r'\d\d:\d\d UTC', '<hh:mm> UTC', value)
        return value

    def name(self, real, placeholder):
        self.names[real] = placeholder

    def step(self, file, method, path, who, body=None, expect=200, alias=None):
        response = call(self.env, method, path, who, body)
        assert response.status_code == expect, (file, response.status_code, response.text)
        data = response.content and response.json() or None
        if alias:
            self.name(data['id'], alias)
        durations = lambda v: {k: ('<ms>' if k == 'duration_ms' and isinstance(x, int) else durations(x)) for k, x in v.items()} if isinstance(v, dict) \
            else [durations(x) for x in v] if isinstance(v, list) else v   # noqa: E731
        self.files[file] = {'request': self.norm({'method': method, 'path': path, 'as': who, 'body': body}), 'status': response.status_code,
                            'response': self.norm(durations(data))}
        return data


