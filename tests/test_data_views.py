def auth(env, who='alice'):
    return {'Authorization': 'Bearer ' + env.sessions[who].access_token}


def call(env, method, path, who='alice', body=None, base=None):
    return env.client.request(method, (base or env.base) + path, headers=auth(env, who), json=body)


def make_view(env, kind, name, body, who='alice', status=201):
    response = call(env, 'POST', '/views', who, {'kind': kind, 'name': name, 'spec': body})
    assert response.status_code == status, response.text
    return response.json()


def table_view(env, name='Big sales', **kw):
    return make_view(env, 'table', name, spec(env.cid, **kw))


def segment(env, name='Big', *filters, who='alice'):
    return make_view(env, 'segment', name, segment_spec(env.cid, *(filters or (F('amount', 'gt', value=100),))), who)


def wait(env, job, who='alice'):
    for _ in range(3000):
        value = call(env, 'GET', '/jobs/' + job['id'], who).json()
        if value['status'] not in {'queued', 'running'}:
            return value
        time.sleep(.005)
    raise AssertionError('job did not finish')


def run(env, vid, who='alice', request_id=None, **body):
    request_id = request_id or f'r-{who}-{time.monotonic_ns()}'
    return call(env, 'POST', f'/views/{vid}/run', who, {'request_id': request_id, **body})


def finished(env, vid, who='alice', **body):
    response = run(env, vid, who, **body)
    assert response.status_code == 200, response.text
    done = wait(env, response.json(), who)
    assert done['status'] == 'completed', done
    return done


def code(response):
    detail = response.json()['detail']
    return detail['code'] if isinstance(detail, dict) else detail


